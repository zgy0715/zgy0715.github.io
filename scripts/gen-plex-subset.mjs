// 从 @ibm/plex-sans-sc 的 all.css 生成精简子集 CSS（仅 400/500/700 字重 + split woff2 分片）。
// 由 package.json 的 postinstall 钩子自动执行，保证 CI 安装后文件存在。
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const pkgRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(pkgRoot, 'node_modules/@ibm/plex-sans-sc/css/ibm-plex-sans-sc-all.css');
const out = join(pkgRoot, 'node_modules/@ibm/plex-sans-sc/css/yzb-subset.css');
const KEEP = new Set(['400', '500', '700']);

let css;
try {
  css = readFileSync(src, 'utf8');
} catch {
  console.log('[gen-plex-subset] @ibm/plex-sans-sc not installed, skip.');
  process.exit(0);
}

const blocks = css.match(/@font-face\s*\{[^}]+\}/g) ?? [];
const kept = [];
for (const b of blocks) {
  const w = /font-weight:\s*(\d+)/.exec(b);
  if (!w || !KEEP.has(w[1])) continue;
  const m = /url\("(\.\.\/fonts\/split\/woff2\/hinted\/[^"]+\.woff2)"\)/.exec(b);
  if (!m) continue;
  const family = /font-family:\s*'([^']+)'/.exec(b)?.[1] ?? 'IBM Plex Sans SC';
  kept.push(`@font-face {\n  font-family: '${family}';\n  font-style: normal;\n  font-weight: ${w[1]};\n  font-display: swap;\n  src: url("${m[1]}") format("woff2");\n}`);
}

writeFileSync(out, '/* generated by scripts/gen-plex-subset.mjs — do not edit */\n' + kept.join('\n') + '\n');
console.log('[gen-plex-subset] generated', kept.length, 'font-face blocks');
